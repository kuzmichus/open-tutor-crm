/**
 * OpenTutorCRM — клиентское состояние диалога окна для записи.
 *
 * Alpine-компонент `slotDialog` монтируется на корне диалога
 * (`slot/_dialog.html`), который приходит в контейнер `#modal` уже
 * отрисованным сервером. JS здесь только переключает режим
 * «Одно окно» / «Несколько дней» и закрывает диалог: и создание, и
 * предпросмотр пачки считает сервер (design.md D6), поэтому в браузере
 * нет ни формулы генерации окон, ни проверки занятости.
 *
 * Подключается на странице календаря до `alpine.min.js` (через
 * `{% block head %}`): подписка на `alpine:init` должна сработать раньше,
 * чем Alpine начнёт обход DOM — тот же паттерн, что у `calendar.js`.
 */
(function () {
  "use strict";

  document.addEventListener("alpine:init", function () {
    Alpine.data("slotDialog", function (initialMode) {
      return {
        /* Диалог приходит свопом уже открытым; закрытие гасит его и
           опустошает контейнер — следующий hx-get отрисует заново. */
        open: true,
        /* Режим создания: "single" — одно окно, "batch" — несколько дней.
           `template x-if` в шаблоне убирает поля другого режима из DOM,
           поэтому в запрос уходят только поля выбранного режима. */
        mode: initialMode === "batch" ? "batch" : "single",
        /* Двухшаговое подтверждение удаления (паттерн `_manage.html`). */
        confirmingDelete: false,

        close: function () {
          /* Устаревший компонент не трогает контейнер.

             Диалог подменяется свопом (`hx-swap="outerHTML"`), а Alpine
             снимает слушатели с удалённого узла отложенно — на следующем
             тике. Поэтому подписка `slot-saved` уже выброшенного диалога
             успевает сработать на событии, которое htmx рассылает после
             подмены, и `modal.innerHTML = ""` стирал только что
             пришедший отчёт о созданной пачке (проверено в браузере:
             отчёт появлялся в DOM и исчезал в том же тике). Проверка
             `isConnected` делает закрытие идемпотентным: закрывает только
             тот диалог, который сейчас в документе. */
          if (!this.$root.isConnected) return;
          this.open = false;
          var modal = document.getElementById("modal");
          if (modal) modal.innerHTML = "";
        },
      };
    });
  });
})();
