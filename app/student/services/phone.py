"""Формат телефона: приведение к виду `+7 555 555-55-55`.

Форматирование живёт на сервере, а не только в браузере: значение сохраняется
в едином виде независимо от того, ввёл ли пользователь `8 555 555 55 55`,
`+7 (555) 555-55-55` или `95555555555`. Клиентский ввод дублирует это правило
для живого форматирования по мере набора (см. `app/static/students.js`).

Номера, которые не похожи на российские (длиннее 11 цифр или 11 цифр с
кодом страны, отличным от 7/8), не переписываются: подгонять чужой формат
под шаблон нельзя.
"""

import re

_NON_DIGITS_RE = re.compile(r"\D")

# Символы, допустимые в записи телефона. Если во вводе есть что-то ещё
# (буквы, `доб. 12`, комментарий), значение не переписывается: молча терять
# часть ввода нельзя.
_PHONE_CHARS_RE = re.compile(r"^[0-9+\-()\s.]+$")

# Российский номер: код страны 7 + 10 цифр.
_PHONE_LENGTH = 11

# Код страны и «междугородний» префикс, которые считаются одним и тем же.
_COUNTRY_CODES = {"7", "8"}


def normalize_phone(value: str | None) -> str:
    """Только цифры: `+7 (555) 555-55-55` → `75555555555`."""
    return _NON_DIGITS_RE.sub("", value or "")


def is_phone_like(value: str | None) -> bool:
    """Похоже ли значение на запись телефона: пусто или только цифры и знаки.

    Буквы, `доб. 12` и прочие посторонние символы телефоном не считаются —
    форма может отклонить такое значение (мини-форма группы, D9).
    """
    raw = (value or "").strip()
    return not raw or bool(_PHONE_CHARS_RE.match(raw))


def format_phone(value: str | None) -> str:
    """Приводит номер к виду `+7 555 555-55-55`.

    Пустое значение остаётся пустым. Незавершённый номер форматируется
    частично (`916` → `+7 916`), чтобы поле не «прыгало» во время набора,
    но разделитель без цифр после него не добавляется.

    Значение возвращается как введено, если оно не похоже на телефон:
    есть посторонние символы (например `доб. 12`), цифр больше 11 или
    11 цифр с кодом страны, отличным от 7/8.
    """
    raw = (value or "").strip()
    if not raw:
        return ""
    if not _PHONE_CHARS_RE.match(raw):
        return raw

    digits = normalize_phone(raw)
    if not digits:
        # Пользователь ещё набирает префикс (`+`, `(`) — не подставляем `+7`
        # раньше времени, иначе при вводе `+7 ...` получится `+7 7 ...`.
        return raw
    if len(digits) > _PHONE_LENGTH:
        return raw

    if digits[0] in _COUNTRY_CODES:
        # Код страны уже есть: и `+7 916...`, и `8 916...`, и недопечатанный
        # номер после удаления символа.
        national = digits[1:]
    elif len(digits) == _PHONE_LENGTH:
        # 11 цифр с чужим кодом страны — формат не навязываем.
        return raw
    else:
        # 10 цифр без кода страны — это местный номер.
        national = digits

    result = "+7"
    if national[0:3]:
        result += " " + national[0:3]
    if national[3:6]:
        result += " " + national[3:6]
    if national[6:8]:
        result += "-" + national[6:8]
    if national[8:10]:
        result += "-" + national[8:10]
    return result
