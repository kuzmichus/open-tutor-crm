"""Автоперевод ученика в «Активные» за первый проведённый платный урок.

Сигнал — строка списания (`kind='lesson'`): она появляется только у
проведённого урока с определимой ценой (design D1 change'а
student-auto-activation), поэтому «пробный на шару» и незаданная цена
активации не дают. Вызывается из путей создания списаний
(`finance/services/charges.py`, `finance/services/recalculate.py`) —
правило перехода при этом живёт в домене ученика, а не в финансах.

Только `new` → `active` (design D2): архив возвращается в работу явным
действием репетитора, «активному» присваивать статус незачем. Без
коммита — как `sync_lesson_charge`: урок, списания и статус сохраняются
одной транзакцией вызывающей стороны.
"""

from sqlalchemy.orm import Session

from app.student.models.student import Student

# Переход затрагивает ровно одну пару статусов; остальные не трогаются.
STATUS_NEW = "new"
STATUS_ACTIVE = "active"


def activate_on_first_charge(db: Session, student_id: str) -> None:
    """Переводит «нового» ученика в «Активные»; без коммита, идемпотентно.

    Повторные вызовы на одном ученике — норма (серия уроков, пересчёт по
    двадцати занятиям), поэтому единственная проверка — текущий статус:
    не «новый» — делать нечего. Несуществующий ученик молча пропускается:
    списание без ученика не существует, а проверка владельца — дело вьюхи.
    """
    student = db.get(Student, student_id)
    if student is None or student.status != STATUS_NEW:
        return
    student.status = STATUS_ACTIVE
