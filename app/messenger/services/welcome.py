"""Приветственное сообщение в только что привязанный канал.

Приходит в чат сразу после подтверждения привязки: репетитор видит, что
канал работает и куда будут приходить уведомления. Отправка идёт через
общий `send_message` (журнал + ретрай); сбой приветствия привязку не
отменяет — ошибки возвращаются списком вызывающему коду.
"""

from sqlalchemy.orm import Session

from app.messenger.services.send import send_message

# Единый текст для всех мессенджеров: бот репетитора здоровается сам.
WELCOME_MESSAGE = (
    "Канал уведомлений Open Tutor CRM подключён. "
    "Теперь здесь будут приходить напоминания об уроках и другие уведомления — "
    "настроить их можно на вкладке «Уведомления»."
)


def send_welcome(
    db: Session, tutor_id: str, messenger: str, chat_id: str
) -> list[str]:
    """Приветствует чат от имени бота; пустой список — доставлено."""
    return send_message(db, tutor_id, messenger, chat_id, WELCOME_MESSAGE)
