"""Исключения модуля messenger: доставка сообщения и чтение данных бота."""


class SendError(Exception):
    """Неудачная отправка сообщения мессенджером.

    Бросается конкретным отправителем (сеть, ответ API с ошибкой),
    ловится декораторами-обёртками (ретрай, журнал) и диспетчером
    `send_message`, который превращает её в элемент списка ошибок.
    """


class BotApiError(Exception):
    """Неудачное чтение данных бота (getMe, getUpdates и аналоги MAX).

    Бросается API-клиентами привязки канала (сеть, ответ API с ошибкой)
    и превращается сервисом привязки в элемент списка ошибок — соглашение
    сервисов проекта. Отдельно от `SendError`: это не доставка, а
    подготовка привязки, ретраить её обёрткой отправки не нужно.
    """
