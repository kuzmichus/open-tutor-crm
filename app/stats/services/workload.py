"""Уровни недельной занятости: комфорт, высокая нагрузка, риск выгорания.

Уровень определяется абсолютными часами общей занятости **в неделю** (уроки
плюс подготовка), а не процентом от календаря: 90% от 90 доступных часов —
это 81 час работы, физически невозможная нагрузка, тогда как 36% тех же
90 часов (32,7 часа) — отличная норма. Поэтому «Загрузка ресурса» красится
по часам, а процент на полосе остаётся справочной цифрой.

Границы: до 35 часов — комфорт, от 35 до 45 — высокая нагрузка, больше
45 — риск выгорания. Ровно 35 и ровно 45 относятся к более мягкому уровню:
следующий уровень начинается со следующей минуты.

Модуль не знает ни про БД, ни про шаблоны: пороги и формулировки — общий
источник правды для шкалы «Загрузка ресурса», подписи-инсайта и алерта
выгорания. Иначе три места разошлись бы в трактовке «много это сколько».
"""

# Дней в неделе: база пересчёта занятости периода в недельную.
WEEK_DAYS = 7

# Пороги недельной общей занятости, часы. Комфорт — строго меньше 35,
# высокая нагрузка — от 35 до 45 включительно, риск выгорания — больше 45.
COMFORT_WEEKLY_HOURS = 35
HIGH_WEEKLY_HOURS = 45

# Уровни нагрузки; ключи используются в шаблонах и тестах.
LEVEL_COMFORT = "comfort"
LEVEL_HIGH = "high"
LEVEL_BURNOUT = "burnout"

# Вердикт для подписи-инсайта: что означает такая недельная нагрузка.
LEVEL_VERDICTS = {
    LEVEL_COMFORT: "Это комфортный уровень нагрузки.",
    LEVEL_HIGH: "Это высокий уровень нагрузки.",
    LEVEL_BURNOUT: "Высокий риск выгорания!",
}


def level(weekly_hours: float) -> str:
    """Уровень недельной общей занятости по абсолютным часам.

    Сравнение идёт по часам, а не по проценту доступного времени: порог
    выгорания — свойство человека, а не его календаря.
    """
    if weekly_hours > HIGH_WEEKLY_HOURS:
        return LEVEL_BURNOUT
    if weekly_hours >= COMFORT_WEEKLY_HOURS:
        return LEVEL_HIGH
    return LEVEL_COMFORT


def verdict(weekly_hours: float) -> str:
    """Готовая фраза-вердикт для инсайта: «Это комфортный уровень нагрузки.»"""
    return LEVEL_VERDICTS[level(weekly_hours)]


def weekly_minutes(total_minutes: int, days: int) -> int:
    """Минуты периода → минуты средней недели; период нулевой длины — 0.

    Порог задан в неделю, а период «Обзора» может быть любым: «Весь период»
    даёт среднюю неделю за всё время, а не последнюю.
    """
    if days <= 0:
        return 0
    return round(total_minutes * WEEK_DAYS / days)
