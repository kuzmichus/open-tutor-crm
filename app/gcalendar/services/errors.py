"""Исключения модуля gcalendar.

Как в `app/messenger/services/errors.py`: сервисы бросают доменные
исключения, а вьюхи превращают их в текст для пользователя. Все они —
`GoogleError`, поэтому вызывающая сторона может ловить одну базу и при
этом различать случаи, где нужно другое поведение.
"""

class GoogleError(Exception):
    """Общая база ошибок интеграции с Google Календарём."""

class GoogleNotConfigured(GoogleError):
    """OAuth-креды не заданы в окружении сервера.

    Это не ошибка пользователя: владелец сервера не заполнил
    `GOOGLE_CLIENT_ID`/`GOOGLE_CLIENT_SECRET`. Карточка в профиле
    показывает подсказку, кнопка подключения неактивна.
    """

class GoogleApiError(GoogleError):
    """Вызов Google не удался: сеть недоступна или API вернул ошибку.

    Ловится синхронизацией: действие пользователя (сохранение урока)
    не должно ломаться из-за недоступности внешнего сервиса, поэтому
    ошибка пишется в лог и в параметр `google_last_error`.
    """

class GoogleUnauthorized(GoogleApiError):
    """401 от API: access_token истёк или отозван.

    Синхронизация обновляет токен по refresh_token и повторяет запрос
    ровно один раз (design D6) — бесконечного цикла ретраев нет.
    """

class GoogleReauthRequired(GoogleApiError):
    """refresh_token больше не действует (`invalid_grant`).

    Пользователь отозвал доступ в аккаунте Google или токен устарел.
    Соединение сбрасывается, карточка предлагает подключиться заново.
    """
