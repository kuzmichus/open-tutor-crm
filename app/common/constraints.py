"""Сборка SQL-условий `IN (...)` для CHECK-ограничений моделей.

Общий код (правило AGENTS.md «общий код — в `common/`»): закрытые списки
значений есть у моделей всех доменов, и текст ограничения собирался
одинаковой функцией в каждом файле модели. Формат строки фиксирован:
Alembic сравнивает метаданные с базой по тексту, поэтому любое изменение
здесь — отдельная миграция, а не «косметика».

Модуль не импортирует ничего из приложения: модели нижнего уровня не
должны тянуть зависимости (иначе первый же циклический импорт).
"""


def sql_string_in(column: str, values: tuple[str, ...]) -> str:
    """`column IN ('a', 'b')` — строковый список для CHECK-ограничения."""
    quoted = ", ".join(f"'{value}'" for value in values)
    return f"{column} IN ({quoted})"


def sql_int_in(column: str, values: tuple[int, ...]) -> str:
    """`column IN (1, 2)` — числовой список для CHECK-ограничения."""
    joined = ", ".join(str(value) for value in values)
    return f"{column} IN ({joined})"
