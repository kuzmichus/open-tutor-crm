"""Публичная ссылка на окна: сборка и разбор (design.md D7).

Ссылка кодирует всё необходимое в самом адресе — отдельной таблицы ссылок
нет:

    /s/<tutor_id>?start=YYYY-MM-DD

`tutor_id` — `uuid4`: перебором не подбирается, поэтому токен не нужен.
`start` — та же семантика, что у календаря: любая дата недели, которая
нормализуется к понедельнику (`week_start`). Новой семантики не вводим —
ссылка на окна и ссылка на неделю календаря устроены одинаково.

Модуль не зависит от сессии: публичная страница не требует входа, и
единственная проверка — существование репетитора (её делает вьюха,
отвечая обычной 404-страницей, design D7).

*Чего ссылка не даёт*: её нельзя отозвать отдельно от окон. Отзыв —
содержимым: снял публичность или удалил окна, страница пуста. Если
понадобится «закрыть страницу целиком», добавим `public_token` в `tutors`
отдельным change'ем, не ломая формат (старый адрес останется алиасом).
"""

from datetime import date

from app.calendar.services.week import week_start

# Префикс публичных адресов: короткий, чтобы ссылку было удобно диктовать.
PUBLIC_PREFIX = "/s"

def public_url(tutor_id: str, monday: date) -> str:
    """Адрес публичной страницы недели `monday` для этого репетитора.

    `monday` нормализуется: в ссылку всегда попадает понедельник, поэтому
    один и тот же адрес не зависит от того, какую дату недели передали.
    """
    return f"{PUBLIC_PREFIX}/{tutor_id}?start={week_start(monday).isoformat()}"

def booking_url(tutor_id: str) -> str:
    """Адрес приёма заявки для этого репетитора (форма на публичной странице)."""
    return f"{PUBLIC_PREFIX}/{tutor_id}/book"

def week_from_start(raw: str | None, today: date) -> date:
    """Понедельник недели из `?start=`; кривое или пустое — неделя `today`.

    Некорректная дата не ошибка страницы (как `?start=` календаря, design
    D4): ученик открывает ссылку из мессенджера, где параметр мог
    обрезаться, — он должен увидеть окна, а не 500.
    """
    if not raw:
        return week_start(today)
    try:
        return week_start(raw)
    except ValueError:
        return week_start(today)
